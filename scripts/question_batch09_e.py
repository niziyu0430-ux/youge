# Only mode metadata and stable IDs are assembled; no scene or option is generated.
def _assemble_modes(identifier,title,scope,written_modes):
 result=deepcopy(written_modes[0][2])
 result['id']=identifier
 result['title']=title
 result['scope']=scope
 result['modes']=[]
 result['editorial_notes']=[]
 for slot in result['slots']:
  slot['id']=identifier.upper()+f"{slot['number']:02}"
  slot['variants']=[]
 for mode,label,written in written_modes:
  initial={}
  for target,original in zip(result['slots'],written['slots']):
   for variant in deepcopy(original['variants']):
    key=variant['id'].rsplit('.',1)[1]
    variant['id']=target['id']+'.'+mode.upper()+'.'+key
    variant['modes']=[mode]
    target['variants'].append(variant)
    if key=='V1':
     initial[target['id']]=variant['id']
  result['modes'].append({'id':mode,'label':label,'initial_variants':initial})
  result['editorial_notes'].extend(written['editorial_notes'])
 return result

