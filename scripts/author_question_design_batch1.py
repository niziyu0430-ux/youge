def question(n, scene, text, options, purpose, sources, requires=(), boundary=''):
    return {'number':n,'scene':scene,'text':text,'response_type':'single',
            'options':[{'id':chr(65+i),'label':label,'proposed_signal':signal} for i,(label,signal) in enumerate(options)],
            'design_purpose':purpose,'source_ids':sources.split(),
            'requires_experience':list(requires),'interpretation_boundary':boundary,
            'status':'editorial_draft','scoring_status':'not_calibrated','alternatives':[]}


def add_pack(identifier,game_ids,title,scope,questions,notes):
    assert len(questions)==12
    for item in questions:item['id']=f'{identifier.upper()}{item["number"]:02d}'
    pack={'id':identifier,'game_ids':game_ids,'title':title,'scope':scope,
          'status':'editorial_draft','player_review':'pending','runtime_enabled':False,
          'notes':notes,'questions':questions}
    PACKS.append(pack)
    return pack


def alternate(pack,number,text,options,purpose,sources):
    item=pack['questions'][number-1]
    assert [signal for _,signal in options]==[o['proposed_signal'] for o in item['options']]
    item['alternatives'].append({'id':item['id']+'.ALT1','text':text,
        'options':[{'id':chr(65+i),'label':label,'proposed_signal':signal} for i,(label,signal) in enumerate(options)],
        'design_purpose':purpose,'source_ids':sources.split(),'requires_experience':[],
        'status':'editorial_draft','equivalence_status':'same_intended_signals_not_empirically_equated'})


