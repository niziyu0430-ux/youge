def S(scene, text, labels, signals, purpose, sources, boundary=BOUNDARY):
    return dict(scene=scene, text=text, labels=labels, signals=signals,
                purpose=purpose, sources=sources, boundary=boundary)


def four(number, living, early, build, cas):
    """Serialize four fully written scenes; no generated question prose."""
    def pair(first, second):
        item = Q(number, first['scene'], first['text'], first['labels'], first['signals'],
                 first['purpose'], first['sources'],
                 (second['text'], second['labels'], second['signals']), first['boundary'])
        for v, authored in zip(item['variants'], (first, second)):
            v.update(scene=authored['scene'], source_ids=authored['sources'].split(),
                     design_purpose=authored['purpose'], interpretation_boundary=authored['boundary'])
        return item
    item = pair(living, early)
    other = pair(build, cas)
    other['variants'][0]['key'] = 'BUILD'
    other['variants'][1]['key'] = 'CAS'
    item['variants'].extend(other['variants'])
    return item


